import com.citacomsys.core.notification.InAppNotificationService
import com.citacomsys.core.ui.BaseViewModel
import com.citacomsys.core.ui.result.UiResult
import com.citacomsys.core.ui.result.asUiResult
import com.citacomsys.core.ui.result.getOrNull
import com.citacomsys.module.inventory.validation.BaseProductValidator
import com.citacomsys.module.inventory.validation.ProductValidationResult
import com.citacomsys.types.BaseProduct
import com.citacomsys.core.domain.service.AppSessionManager
import com.citacomsys.feature.api.telemetry.TelemetryLogClient
import com.citacomsys.types.ProductType
import com.citacomsys.types.generateUUID
import io.github.aakira.napier.Napier
import kotlinx.coroutines.flow.MutableStateFlow
import kotlinx.coroutines.flow.asStateFlow
import kotlinx.coroutines.flow.combine
import kotlinx.coroutines.launch
import kotlin.time.Instant
import kotlin.time.Clock

/**
 * ViewModel for managing the creation and editing of products.
 * Includes app-aware templates based on business type (Pharmacy, Retail, etc.).
 */
abstract class BaseProductFormViewModel<T : BaseProduct>(
    notification: InAppNotificationService,
    protected val sessionManager: AppSessionManager,
    protected val telemetryClient: TelemetryLogClient
) : BaseViewModel(notification) {

    val activeProductType: ProductType = sessionManager.activeProductType

    protected val _formError = MutableStateFlow<List<String>>(emptyList())
    val formError = _formError.asStateFlow()

    protected val _productState = MutableStateFlow<UiResult<T>>(UiResult.Idle)
    val productState = _productState.asStateFlow()

    protected val _saveState = MutableStateFlow<UiResult<Unit>>(UiResult.Idle)
    val saveState = _saveState.asStateFlow()

    // To prevent double submission of the same product
    protected var newProductId: String = generateUUID()

    // --- Form State ---
    val name = MutableStateFlow("")
    val sku = MutableStateFlow("")
    val barcode = MutableStateFlow("")
    val brandName = MutableStateFlow("")
    val category = MutableStateFlow("")
    val unitOfMeasure = MutableStateFlow("Piece")
    val reorderLevel = MutableStateFlow("10")
    val description = MutableStateFlow("")

    // Flag tracking if user manually entered/edited the SKU field
    var isUserInput: Boolean = false
        protected set

    // --- Templates Logic ---
    protected val _templates = MutableStateFlow<List<ProductTemplate>>(emptyList())
    val templates = _templates.asStateFlow()

    init {
        Napier.d(
            tag = "BaseProductFormViewModel",
            message = "Initializing: Active Product Type = $activeProductType"
        )
        loadTemplates()
    }

    /**
     * Called when the user types directly into the SKU input field.
     * Sets [isUserInput] to true if non-blank, so automatic updates do not override manual input.
     */
    fun onSkuInputChanged(newSku: String) {
        sku.value = newSku
        isUserInput = newSku.trim().isNotEmpty()
    }

    protected open fun observeFormFieldsForAutoSku() {
        viewModelScope.launch {
            combine(name, brandName, category) { _, _, _ -> }
                .collect {
                    updateAutoGeneratedSku()
                }
        }
    }

    open fun updateAutoGeneratedSku() {
        if (isUserInput) return
        val textToUse = buildSkuInputText()
        if (textToUse.isNotBlank()) {
            sku.value = generateHumanReadableSkuFromText(textToUse)
        } else {
            sku.value = ""
        }
    }

    protected open fun buildSkuInputText(): String {
        return listOf(name.value.trim(), brandName.value.trim(), category.value.trim())
            .filter { it.isNotBlank() }
            .joinToString(" ")
    }

    /**
     * Generates a short, human-identifiable SKU based on product text attributes.
     * Examples:
     *   "Panadol Paracetamol 500mg Tablet" -> PNDL-500-TAB
     *   "V-Neck T-Shirt, Blue Medium" -> VNK-BLU-M
     */
    fun generateHumanReadableSkuFromText(text: String): String {
        val rawText = text.trim()
        if (rawText.isBlank()) return ""

        val tokens = rawText.split(Regex("[\\s,._\\-/]+")).filter { it.isNotBlank() }
        val parts = mutableListOf<String>()

        for (token in tokens) {
            val uppercaseToken = token.uppercase()

            if (uppercaseToken.matches(Regex("T\\d+")) || uppercaseToken.matches(Regex("\\d+S"))) {
                parts.add(uppercaseToken)
                continue
            }

            val numberMatch = Regex("(\\d+)").find(token)
            if (numberMatch != null && parts.none { it.matches(Regex("\\d+.*")) }) {
                parts.add(numberMatch.groupValues[1])
                continue
            }

            when (uppercaseToken) {
                "S", "SMALL" -> {
                    if (!parts.contains("S")) parts.add("S"); continue
                }

                "M", "MEDIUM" -> {
                    if (!parts.contains("M")) parts.add("M"); continue
                }

                "L", "LARGE" -> {
                    if (!parts.contains("L")) parts.add("L"); continue
                }

                "XL", "EXTRA" -> {
                    if (!parts.contains("XL")) parts.add("XL"); continue
                }

                "XXL" -> {
                    if (!parts.contains("XXL")) parts.add("XXL"); continue
                }

                "BLUE", "BLU" -> {
                    if (!parts.contains("BLU")) parts.add("BLU"); continue
                }

                "RED" -> {
                    if (!parts.contains("RED")) parts.add("RED"); continue
                }

                "BLACK", "BLK" -> {
                    if (!parts.contains("BLK")) parts.add("BLK"); continue
                }

                "WHITE", "WHT" -> {
                    if (!parts.contains("WHT")) parts.add("WHT"); continue
                }

                "GREEN", "GRN" -> {
                    if (!parts.contains("GRN")) parts.add("GRN"); continue
                }

                "TABLET", "TABLETS", "TAB" -> {
                    if (!parts.contains("TAB")) parts.add("TAB"); continue
                }

                "CAPSULE", "CAPSULES", "CAP" -> {
                    if (!parts.contains("CAP")) parts.add("CAP"); continue
                }

                "SYRUP", "SYR" -> {
                    if (!parts.contains("SYR")) parts.add("SYR"); continue
                }
            }

            if (uppercaseToken in setOf("SHIRT", "TSHIRT", "ITEM", "PRODUCT", "GENERIC")) continue

            val code = abbreviateWord(uppercaseToken)
            if (code.isNotBlank() && !parts.contains(code) && parts.size < 4) {
                parts.add(code)
            }
        }

        if (parts.isEmpty()) return ""
        return parts.take(4).joinToString("-")
    }

    private fun abbreviateWord(word: String): String {
        val clean = word.filter { it.isLetter() }
        if (clean.length <= 3) return clean.uppercase()

        val first = clean.first().uppercaseChar()
        val vowels = setOf('A', 'E', 'I', 'O', 'U', 'Y')
        val consonants = clean.drop(1).uppercase().filter { it !in vowels }

        val abbreviated = (first + consonants)
        return if (abbreviated.length >= 3) abbreviated.take(4) else clean.take(4).uppercase()
    }

    protected open fun loadTemplates() {
        // Subclasses can implement business-specific template isLoading
    }

    abstract suspend fun getById(id: String): Result<T>
    abstract suspend fun create(product: T): Result<Unit>
    abstract suspend fun update(product: T): Result<Unit>

    open fun onValidate(p: T) {
        val validator = BaseProductValidator()
        val result = validator.validate(p)
        if (result is ProductValidationResult.Failure) {
            _formError.value = result.messages
        } else {
            _formError.value = emptyList()
        }
    }

    /**
     * Loads an existing product into the form.
     */
    open fun loadProduct(productId: String?) {
        if (productId == null) {
            clearForm()
            return
        }

        viewModelScope.launch {
            _productState.value = UiResult.Loading
            val result = getById(productId)
            _productState.value = result.asUiResult()

            result.onSuccess { product ->
                mapProductToForm(product)
            }
        }
    }

    protected open fun mapProductToForm(product: T) {
        name.value = product.name
        sku.value = product.sku ?: ""
        isUserInput = !product.sku.isNullOrBlank()
        barcode.value = product.barcode ?: ""
        brandName.value = product.brandName
        category.value = product.category ?: ""
        unitOfMeasure.value = product.unitOfMeasure
        reorderLevel.value = product.reorderLevel.toString()
        description.value = product.description ?: ""
    }

    /**
     * Applies a predefined template to the form.
     */
    open fun applyTemplate(template: ProductTemplate) {
        name.value = template.name
        category.value = template.category
    }

    /**
     * Resolves the SKU for the product.
     * Returns trimmed user SKU if entered, or the generated human-readable SKU (or null if both empty).
     */
    fun resolveSku(): String? {
        val userSku = sku.value.trim()
        if (userSku.isNotEmpty()) return userSku
        val autoSku = generateHumanReadableSkuFromText(buildSkuInputText())
        return autoSku.ifBlank { null }
    }

    /**
     * Collects form state and persists to the repository.
     */
    open fun saveProduct(onSuccess: () -> Unit) {
        viewModelScope.launch {
            _saveState.value = UiResult.Loading

            val currentProduct = _productState.value.getOrNull()
            val now = Clock.System.now()

            val productToSave = createProductFromForm(currentProduct, now)

            val result = if (productToSave.id.isEmpty()) {
                create(productToSave)
            } else {
                update(productToSave)
            }

            result.onSuccess {
                val actionLabel = if (productToSave.id.isEmpty()) "CREATE" else "UPDATE"
                telemetryClient.trackApplicationEvent(
                    actorId = sessionManager.currentUserId!!,
                    entityType = "PRODUCT",
                    entityId = productToSave.id.ifEmpty { newProductId },
                    action = actionLabel,
                    summary = "${if (actionLabel == "CREATE") "Created" else "Updated"} product: ${productToSave.name}"
                )
                showSuccess("Product saved successfully")
                onSuccess()
            }.onFailure {
                showError(it.message ?: "Failed to save product")
                _saveState.value = UiResult.Error(it.message ?: "Unknown error")
            }
        }
    }

    protected abstract fun createProductFromForm(
        currentProduct: T?,
        now: Instant
    ): T

    protected open fun clearForm() {
        isUserInput = false
        name.value = ""
        sku.value = ""
        barcode.value = "CITAS-${generateUUID().take(8).uppercase()}"
        brandName.value = ""
        category.value = ""
        unitOfMeasure.value = "Piece"
        reorderLevel.value = "10"
        description.value = ""
        newProductId = generateUUID()
    }
}

data class ProductTemplate(
    val name: String,
    val category: String,
    val genericName: String? = null,
    val dosageForm: String? = null,
    val strength: String? = null,
    val requiresPrescription: Boolean = false
)
