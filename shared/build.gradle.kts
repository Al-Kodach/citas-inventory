plugins {
    alias(libs.plugins.citacomsysKmpLibrary)
}


val app_version: String by project

//  Define a modern, isolated configuration-cache compliant task class
abstract class GenerateBuildVersionConfigTask : DefaultTask() {
    @get:Input
    abstract val appVersion: Property<String>

    @get:OutputDirectory
    abstract val outputDirectory: DirectoryProperty

    @TaskAction
    fun execute() {
        val version = appVersion.get()
        val buildConfigFile = outputDirectory.file("com/citacomsys/shared/BuildVersionConfig.kt").get().asFile

        buildConfigFile.parentFile.mkdirs()
        buildConfigFile.writeText("""
            package com.citacomsys.shared
            
            // This class is auto-generated by the Gradle build system pipeline.
            object BuildVersionConfig {
                const val APP_VERSION = "$version"
            }
        """.trimIndent())
    }
}

//  Register the task and pipe the properties cleanly
val generateBuildVersionConfig = tasks.register<GenerateBuildVersionConfigTask>("generateBuildVersionConfig") {
    description = " Register the task and pipe the properties"
    appVersion.set(app_version)
    outputDirectory.set(layout.buildDirectory.dir("generated/source/version/main/kotlin"))
}

kotlin {
    sourceSets {
        commonMain {
            // Use flatMap to read the directory output provider cleanly without breaking the cache graph
            kotlin.srcDir(generateBuildVersionConfig.flatMap { it.outputDirectory })
            dependencies {
                api(libs.kotlinx.serialization.core)
                api(libs.kotlinx.serialization.json)
                implementation(libs.filekit.core)
                implementation(project(":feature:organization:api"))
            }
        }
        androidMain.dependencies {
            implementation(project(":types-jvm"))
        }
        jvmMain.dependencies {
            implementation(project(":types-jvm"))
        }
    }
}

//  Maintain task compilation dependency chains cleanly
tasks.withType<org.jetbrains.kotlin.gradle.tasks.KotlinCompile>().configureEach {
    dependsOn(generateBuildVersionConfig)
}


