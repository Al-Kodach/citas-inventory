    // --- Pharmacy Specific State ---
    val genericName = MutableStateFlow("")
    val dosageForm = MutableStateFlow("")
    val strength = MutableStateFlow("")
    val requiresPrescription = MutableStateFlow(false)
    val therapeuticClass = MutableStateFlow("")
    val fdaNumber = MutableStateFlow("")

    init {
        observeFormFieldsForAutoSku()
    }

    override fun buildSkuInputText(): String {
        val baseName = name.value.ifBlank { genericName.value }
        return listOf(baseName, brandName.value, strength.value, dosageForm.value)
            .filter { it.isNotBlank() }
            .joinToString(" ")
    }

    override fun observeFormFieldsForAutoSku() {
        viewModelScope.launch {
            combine(name, brandName, genericName, dosageForm, strength) { _, _, _, _, _ -> }
                .collect {
                    updateAutoGeneratedSku()
                }
        }
    }

    override fun applyTemplate(template: ProductTemplate) {
        super.applyTemplate(template)

        genericName.value = template.genericName ?: ""
        dosageForm.value = template.dosageForm ?: ""
        strength.value = template.strength ?: ""
        requiresPrescription.value = template.requiresPrescription

        // Direct mapping from the template category to the core schema enum
        val classification = TherapeuticClassification.fromCategory(template.category)
        therapeuticClass.value = classification?.dbValue ?: ""

        fdaNumber.value = when (template.requiresPrescription) {
            true -> "FDA-RX-PENDING"
            false -> "FDA-OTC-PENDING"
        }
    }

    override fun onValidate(p: PharmacyProduct) {
        super.onValidate(p)
        PharmacyProductExtValidator().validatePharmacy(p).let {
            if (it is ProductValidationResult.Failure) {
                val baseError = super.formError.value
                _formError.value = baseError + it.messages
            }
        }
    }

    override suspend fun getById(id: String): Result<PharmacyProduct> {
        return productRepo.getById(id)
    }

    override suspend fun create(product: PharmacyProduct): Result<Unit> {
        val user = sessionManager.appUser.value ?: error("No active user session")
        try {
            quotaGuard.verifyProductCreationAllowed()
            val result = productRepo.createProduct(
                product = product.copy(
                    id = newProductId,
                    type = ProductType.PHARMACY,
                    workspaceId = sessionManager.activeWorkspaceId!!
                ),
                actorId = user.id,
                actorName = user.name
            )
            if (result.isSuccess) {
                quotaGuard.consumeLocalResource(
                    ResourceType.PRODUCT,
                    workspaceId = sessionManager.activeWorkspaceId!!
                )
            }
            return result
        } catch (e: Exception) {
            return Result.failure(e)
        }
    }

    override suspend fun update(product: PharmacyProduct): Result<Unit> {
        val user = sessionManager.appUser.value ?: error("No active user session")
        val request = PharmacyMetadataUpdateRequest(
            workspaceId = product.workspaceId,
            name = product.name.trim(),
            brandName = product.brandName.trim(),
            sku = product.sku?.trim()?.takeIf { it.isNotBlank() },
            barcode = product.barcode?.trim()?.takeIf { it.isNotBlank() },
            description = product.description?.trim()?.takeIf { it.isNotBlank() },
            genericName = product.genericName?.trim()?.takeIf { it.isNotBlank() },
            dosageForm = product.dosageForm?.trim()?.takeIf { it.isNotBlank() },
            unitOfMeasure = product.unitOfMeasure.trim(),
            category = product.category?.trim()?.takeIf { it.isNotBlank() },
            reorderLevel = product.reorderLevel,
            strength = product.strength?.trim()?.takeIf { it.isNotBlank() },
            requiresPrescription = product.requiresPrescription,
            therapeuticClass = product.therapeuticClass?.trim()?.takeIf { it.isNotBlank() },
            fdaNumber = product.fdaNumber?.trim()?.takeIf { it.isNotBlank() }
        )
        return productRepo.updatePharmacyMetadata(
            productId = product.id,
            request = request,
            actorId = user.id,
            actorName = user.name
        )
    }

    override fun mapProductToForm(product: PharmacyProduct) {
        super.mapProductToForm(product)
        genericName.value = product.genericName ?: ""
        dosageForm.value = product.dosageForm ?: ""
        strength.value = product.strength ?: ""
        requiresPrescription.value = product.requiresPrescription
        therapeuticClass.value = product.therapeuticClass ?: ""
        fdaNumber.value = product.fdaNumber ?: ""
    }

    override fun createProductFromForm(
        currentProduct: PharmacyProduct?,
        now: Instant
    ): PharmacyProduct {
        return Pharmacy(
            id = currentProduct?.id ?: "",
            workspaceId = currentProduct?.workspaceId ?: "",
            name = name.value.trim(),
            brandName = brandName.value.trim(),
            sku = resolveSku(),
            barcode = barcode.value.trim().takeIf { it.isNotBlank() },
            description = description.value.trim().takeIf { it.isNotBlank() },
            unitOfMeasure = unitOfMeasure.value.trim().ifEmpty { "Piece" },
            category = category.value.trim().takeIf { it.isNotBlank() },
            reorderLevel = reorderLevel.value.trim().toIntOrNull() ?: 10,
            isActive = currentProduct?.isActive ?: true,
            createdAt = currentProduct?.createdAt ?: now,
            updatedAt = now,

            // Pharmacy Extension - Trimmed & null if blank
            genericName = genericName.value.trim().takeIf { it.isNotBlank() },
            dosageForm = dosageForm.value.trim().takeIf { it.isNotBlank() },
            strength = strength.value.trim().takeIf { it.isNotBlank() },
            requiresPrescription = requiresPrescription.value,
            therapeuticClass = therapeuticClass.value.trim().takeIf { it.isNotBlank() },
            fdaNumber = fdaNumber.value.trim().takeIf { it.isNotBlank() }
        )
    }

